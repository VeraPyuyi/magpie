func TestDotQueueCanonicalBytes(t *testing.T) {
	fixture, err := os.ReadFile("testdata/queue-canonical.json")
	if err != nil {
		t.Fatal(err)
	}
	fixture = bytes.TrimSpace(fixture)
	var sub Submission
	if err := json.Unmarshal(fixture, &sub); err != nil {
		t.Fatal(err)
	}
	got, err := Digest(sub)
	if err != nil {
		t.Fatal(err)
	}
	want := fmt.Sprintf("%x", sha256.Sum256(fixture))
	if want != "041e2b80b9c6815f41f537cd693374709ee3a2a5e08ccc3627320f19764fb51b" || got != want {
		t.Fatalf("canonical byte fixture: got=%s fixture=%s", got, want)
	}
}

// Golden values were generated by running the actual DotControl
// internal/dotqueue/digest.go submissionDigest, copied unchanged into a
// standalone temporary harness. These values do not depend on client types.
func TestDotDigestMatchesQueue(t *testing.T) {
	for _, tc := range []struct {
		sub  Submission
		want string
	}{
		{Submission{RequestID: "req-a", Mode: "answer", SessionID: "sess-b"}, "d3e6afc8c3a08fb4f6a070e6cf66edf7135226c8f84d5e799521d0ebd904ef0f"},
		{Submission{RequestID: "req-x", Mode: "task", SessionID: "sess-y", Messages: []Message{{"system", "<规则>&\n"}, {"user", "你好 😀"}}, Task: "执行\t任务"}, "041e2b80b9c6815f41f537cd693374709ee3a2a5e08ccc3627320f19764fb51b"},
	} {
		got, err := Digest(tc.sub)
		if err != nil || got != tc.want {
			t.Fatalf("queue golden: got %s want %s error %v", got, tc.want, err)
		}
	}
	sub := testSubmission()
	sub.Messages = append(sub.Messages, Message{"assistant", "hi"})
	a, _ := Digest(sub)
	sub.Messages[0], sub.Messages[1] = sub.Messages[1], sub.Messages[0]
	b, _ := Digest(sub)
	if a == b {
		t.Fatal("role order must change digest")
	}
}

func TestJobAndStatusSummaryCapacityFields(t *testing.T) {
	job := Job{Summary: "waiting for operator"}
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(mustMarshal(job), &raw); err != nil || string(raw["summary"]) != `"waiting for operator"` {
		t.Fatalf("job summary %#v", raw)
	}
	status := Status{Capacity: &Capacity{Limit: 100, Retained: 1, Remaining: 99}}
	if err := json.Unmarshal(mustMarshal(status), &raw); err != nil || string(raw["capacity"]) == "" {
		t.Fatalf("status capacity %#v", raw)
	}
}

func mustMarshal(v any) []byte {
	b, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	return b
}
